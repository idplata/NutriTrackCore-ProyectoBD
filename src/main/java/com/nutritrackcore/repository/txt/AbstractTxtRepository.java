package com.nutritrackcore.repository.txt;

import com.nutritrackcore.exceptions.PersistenceExceptions;
import java.time.format.DateTimeParseException;
import java.util.ArrayList;
import java.util.List;
import java.util.function.ToIntFunction;

/**
 * Base común para los repositorios .txt de una sola tabla.
 * <p>
 * Resuelve lo que todos repiten: leer todas las líneas, validar la cantidad de
 * campos, convertir cada línea en objeto (y al revés) y reescribir el archivo
 * completo. Cada subclase solo define cómo se convierte su entidad.
 *
 * @param <T> tipo de entidad que guarda el repositorio
 */
public abstract class AbstractTxtRepository<T> {

    /** Acceso al archivo .txt de la tabla. */
    protected final TxtFile file;

    /** Nombre del archivo, solo para los mensajes de error. */
    private final String fileName;

    /** Cantidad exacta de campos que debe tener cada línea. */
    private final int fieldCount;

    /**
     * @param file       archivo ya preparado
     * @param fileName   nombre del archivo para los mensajes de error
     * @param fieldCount cantidad de campos por línea
     */
    protected AbstractTxtRepository(TxtFile file, String fileName, int fieldCount) {
        this.file = file;
        this.fileName = fileName;
        this.fieldCount = fieldCount;
    }

    /**
     * Convierte una entidad en una línea del archivo.
     *
     * @param item entidad a convertir
     * @return la línea con los campos separados por {@code "|"}
     * @throws IllegalArgumentException si algún campo contiene {@code "|"} o saltos de línea
     */
    protected abstract String toLine(T item);

    /**
     * Convierte los campos de una línea en una entidad. Puede lanzar
     * {@link IllegalArgumentException} o {@link DateTimeParseException}; la
     * base los convierte en {@link PersistenceExceptions}.
     *
     * @param c campos de la línea, ya separados y con la cantidad correcta
     * @return la entidad leída
     */
    protected abstract T fromFields(String[] c);

    /**
     * Lee todas las entidades del archivo.
     *
     * @return lista modificable con todas las entidades
     * @throws PersistenceExceptions si el archivo no se puede leer o alguna línea es inválida
     */
    protected List<T> readAll() throws PersistenceExceptions {
        List<T> all = new ArrayList<>();
        for (String line : file.readLines()) {
            String[] c = TxtFormat.split(line);
            if (c.length != fieldCount) {
                throw new PersistenceExceptions("Línea inválida en " + fileName + ": " + line);
            }
            try {
                all.add(fromFields(c));
            } catch (DateTimeParseException | IllegalArgumentException e) {   // incluye NumberFormatException
                throw new PersistenceExceptions("Línea corrupta en " + fileName + ": " + line, e);
            }
        }
        return all;
    }

    /**
     * Reescribe el archivo completo con las entidades recibidas. Arma todo el
     * texto antes de tocar el archivo.
     *
     * @param items entidades que quedarán en el archivo
     * @throws PersistenceExceptions si algún texto no se puede guardar o falla la escritura
     */
    protected void writeAll(List<T> items) throws PersistenceExceptions {
        List<String> lines = new ArrayList<>();
        try {
            for (T item : items) {
                lines.add(toLine(item));
            }
        } catch (IllegalArgumentException e) {
            throw new PersistenceExceptions("No se puede guardar: " + e.getMessage(), e);
        }
        file.rewrite(lines);
    }

    /**
     * Calcula el siguiente id autogenerado (equivale a {@code generated by
     * default as identity} en la base de datos).
     *
     * @param items entidades existentes
     * @param idOf  función que extrae el id de cada entidad
     * @return el id mayor más uno, o 1 si no hay entidades
     */
    protected int nextId(List<T> items, ToIntFunction<T> idOf) {
        List<Integer> ids = new ArrayList<>();
        for (T item : items) {
            ids.add(idOf.applyAsInt(item));
        }
        return IdGenerator.next(ids);
    }
}
