CREATE TABLE Usuario_Condicion (
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    id_condicion int not null
        references CondicionMedica (id_condicion) on delete restrict,
    fecha_diagnostico  date
        constraint ck_usuariocondicion_fecha check (fecha_diagnostico <= current_date),
    observaciones varchar,
    primary key (id_usuario, id_condicion)
);

CREATE TABLE Usuario_Alergia (
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    id_alergia int not null
        references Alergia (id_alergia) on delete restrict,
    severidad varchar(20)
        constraint usuarioalergia_severidad check (severidad in ('leve', 'moderada', 'severa')),
    observaciones  varchar,
    primary key (id_usuario, id_alergia)
);

-- Enlace puro entre dos catálogos: si desaparece uno, el enlace no tiene sentido.
CREATE TABLE Alergia_Alimento (
    id_alergia int not null
        references Alergia (id_alergia) on delete cascade,
    id_alimento int not null
        references Alimento (id_alimento) on delete cascade,
    primary key (id_alergia, id_alimento)
);

CREATE TABLE Usuario_AlimentoExcluido (
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    id_alimento int not null
        references Alimento (id_alimento) on delete restrict,
    primary key (id_usuario, id_alimento)
);

-- Un mismo alimento puede repetirse en un plan si es en comidas distintas.
CREATE TABLE PlanDieta_Alimento (
    id_plan int not null
        references PlanDieta (id_plan) on delete cascade,
    id_alimento int not null
        references Alimento (id_alimento) on delete restrict,
    id_tipo_comida  int not null
        references TipoComida (id_tipo_comida) on delete restrict,
    cantidad_g numeric(6,2) not null
        constraint plandietaalimento_cantidad_positiva check (cantidad_g > 0),
    primary key (id_plan, id_alimento, id_tipo_comida)
);

CREATE TABLE RutinaEjercicio_Ejercicio (
    id_rutina int not null
        references RutinaEjercicio (id_rutina) on delete cascade,
    id_ejercicio  int not null
        references Ejercicio (id_ejercicio) on delete restrict,
    series int not null
        constraint rutinaejercicio_series_positiva check (series > 0),
    repeticiones int not null
        constraint rutinaejercicio_repeticiones_positivas check (repeticiones > 0),
    primary key (id_rutina, id_ejercicio)
);

CREATE TABLE SeguimientoRutina (
    id_seguimiento int generated by default as identity primary key,
    id_rutina int not null
        references RutinaEjercicio (id_rutina) on delete cascade,
    fecha_sesion date not null default current_date,
    duracion_min  int not null
        constraint seguimiento_duracion_positivo check (duracion_min > 0),
    completada boolean not null,
    observaciones varchar
);