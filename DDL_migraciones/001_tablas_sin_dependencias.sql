-- 001 tablas sin dependencias

-- Datos de autenticación y demográficos del usuario.
-- peso_kg y altura_cm son los valores ACTUALES;

CREATE TABLE Usuario (
    id_usuario int generated by default as identity primary key,
    nombre varchar(100) not null,
    email varchar(100) not null
        constraint usuario_email_unico unique
        constraint usuario_email_formato_arroba check (email like '%_@_%'),
    contrasena_hash varchar(255) not null,
    peso_kg numeric(5,2) not null
        constraint usuario_peso_poditivo check (peso_kg > 0),
    altura_cm numeric(5,2) not null
        constraint usuario_altura_positiva check (altura_cm > 0),
    fecha_nacimiento date not null
        constraint usuario_nacimiento_menor_fecha_actual check (fecha_nacimiento <= current_date),
    sexo char(1) not null
        constraint usuario_sexo check (sexo in ('M', 'F', 'O')),
    fecha_registro date not null default now(),
    fecha_aceptacion_datos  date not null,
    version_politica varchar(10) not null
);

-- Catálogo cerrado de condiciones médicas.
CREATE TABLE CondicionMedica (
    id_condicion int generated by default as identity primary key,
    nombre varchar(100) not null
        constraint condicionmedica_nombre_unica unique,
    descripcion varchar
);

-- Catálogo cerrado de alergias alimentarias.
CREATE TABLE Alergia (
    id_alergia int generated by default as identity primary key,
    nombre varchar(100) not null
        constraint alergia_nombre_unico unique,
    descripcion varchar
);

-- Catálogo maestro de alimentos; valores nutricionales por 100 g.
CREATE TABLE Alimento (
    id_alimento int generated by default as identity primary key,
    nombre varchar(100) not null
        constraint alimento_nombre_unico unique,
    densidad_g_cm3 numeric(5,3)
        constraint alimento_densidad_positiva check (densidad_g_cm3 > 0),
    calorias_100g  numeric(6,2) not null
        constraint alimento_calorias_positiva check (calorias_100g >= 0),
    proteinas_100g numeric(5,2)
        constraint alimento_proteinas_poitivo check (proteinas_100g >= 0),
    carbohidratos_100g  numeric(5,2)
        constraint alimento_carbohidratos_positivo check (carbohidratos_100g >= 0),
    grasas_100g numeric(5,2)
        constraint alimento_grasas_positiva check (grasas_100g >= 0)
);

-- Catálogo cerrado de momentos del día para las ingestas.
CREATE TABLE TipoComida (
    id_tipo_comida  int generated by default as identity primary key,
    nombre varchar(30) not null
        constraint tipocomida_nombre_unico unique,
    orden_dia int not null
        constraint tipocomida_orden_unico unique
        constraint tipocomida_orden_positivo check (orden_dia > 0)
);

-- Catálogo cerrado de ejercicios.
CREATE TABLE Ejercicio (
    id_ejercicio int generated by default as identity primary key,
    nombre varchar(100) not null
        constraint ejercicio_nombre_unico unique,
    grupo_muscular varchar(50),
    bajo_impacto boolean not null
);