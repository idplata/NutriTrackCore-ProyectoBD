-- 002 tablas dependientes

-- Relación 1:1 con Usuario: id_usuario es PK y FK a la vez.
CREATE TABLE PerfilUsuario (
    id_usuario int primary key
        references Usuario (id_usuario) on delete cascade,
    nivel_actividad varchar(20) not null
        constraint perfil_nivel_actividad
        check (nivel_actividad in ('sedentario', 'ligero', 'moderado', 'muy_activo')),
    experiencia_ejercicio varchar(20) not null
        constraint perfil_experiencia
        check (experiencia_ejercicio in ('principiante', 'intermedio', 'avanzado')),
    objetivo_peso varchar(20) not null
        constraint perfil_objetivo
        check (objetivo_peso in ('bajar', 'mantener', 'subir')),
    dias_entrenamiento_semana  int not null
        constraint perfil_dias_semana check (dias_entrenamiento_semana between 0 and 7),
    minutos_por_sesion int not null
        constraint perfil_minutos_positivo check (minutos_por_sesion > 0),
    lugar_entrenamiento varchar(20) not null
        constraint perfil_lugar_entrenamiento check (lugar_entrenamiento in ('casa', 'gimnasio')),
    tipo_dieta varchar(30) not null
        constraint perfil_tipo_dieta
        check (tipo_dieta in ('normal', 'vegetariana', 'vegana')),
    comidas_al_dia int not null
        constraint perfil_comidas_diarias check (comidas_al_dia between 1 and 8),
    presupuesto varchar(20) not null
        constraint perfil_presupuesto_validacion check (presupuesto in ('bajo', 'medio', 'alto')),
    fecha_actualizacion date not null default current_date
);

-- Restricciones clínicas que cada condición impone a dieta y rutina.
CREATE TABLE ReglaCondicion (
    id_regla int generated by default as identity primary key,
    id_condicion int not null
        references CondicionMedica (id_condicion) on delete cascade,
    tipo_regla varchar(30) not null
        constraint regla_tipo_validacion
        check (tipo_regla in ('maximo_nutriente', 'minimo_nutriente', 'solo_bajo_impacto')),
    nutriente varchar(30)
        constraint regla_nutriente_tipo
        check (nutriente in ('calorias', 'proteinas', 'carbohidratos', 'grasas')),
    valor_limite numeric(6,2)
        constraint regla_valor_positivo check (valor_limite > 0),
    descripcion varchar not null
);

-- Consumo estimado por visión artificial (una fila por alimento reconocido).
CREATE TABLE RegistroConsumo (
    id_registro int generated by default as identity primary key,
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    id_alimento int not null
        references Alimento (id_alimento) on delete restrict,
    imagen varchar(255),
    nivel_estimacion  numeric(5,2)
        constraint registro_nivel_positivo_menor_100 check (nivel_estimacion between 0 and 100),
    gramos_estimados  numeric(6,2) not null
        constraint registro_gramos_positivo check (gramos_estimados > 0),
    fecha_hora date not null default now()
);

CREATE TABLE PlanDieta (
    id_plan int generated by default as identity primary key,
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    fecha_generacion date not null default current_date,
    calorias_objetivo numeric(7,2) not null
        constraint plandieta_calorias_positivo check (calorias_objetivo > 0),
    activo boolean not null default true
);

CREATE TABLE RutinaEjercicio (
    id_rutina int generated by default as identity primary key,
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    fecha_generacion date not null default current_date,
    nivel_intensidad varchar(20) not null
        constraint rutina_intensidad_validacion check (nivel_intensidad in ('bajo', 'moderado', 'alto')),
    activa boolean not null default true
);

-- Mediciones históricas de peso y altura (el IMC se calcula, no se guarda).
CREATE TABLE Historial_IMC (
    id_historial int generated by default as identity primary key,
    id_usuario int not null
        references Usuario (id_usuario) on delete cascade,
    peso_kg numeric(5,2) not null
        constraint historial_peso_positivo check (peso_kg > 0),
    altura_cm numeric(5,2) not null
        constraint historial_altura_positiva check (altura_cm > 0),
    fecha_registro date not null default now()
);